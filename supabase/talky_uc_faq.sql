(학생 경험담 · 2026.11.13)

Q. 긴급 인터뷰는 누구나 신청하나요?
A. 프로그램 시작 2주 이내에 예약 자체가 불가능한 경우에만 가능하다는 내용이 공유됐어요. 대사관 안내를 확인하세요.
(학생 경험담 · 2026.11.12)

Q. 인터뷰 후 비자는 얼마나 걸리나요?
