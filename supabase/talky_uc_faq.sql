Q. 세 캠퍼스에 같은 전공을 써야 하나요?
A. 아니요. 캠퍼스마다 다른 전공을 쓴 사례가 있어요.
(학생 경험담 · 2026.07.23)

Q. Study plan의 course number에는 무엇을 적나요?
A. 수업명 옆 숫자를 적고 알파벳은 suffix에 적어요. 예: ART 1A는 number 1, suffix A.
(학생 경험담 · 2026.07.24)

Q. 선수과목 체크시트는 비슷한 과목이면 다 체크하나요?
A. 실제로 들은 과목만 체크했다는 사례가 많아요. 국제처 문의 후 들은 과목에만 체크했다는 답도 있어요.
(학생 경험담 · 2026.07.23)

Q. 다음 학기에 들을 선수과목은 어떻게 적나요?
A. 선수과목 폼에 적고 수강 예정이라고 표시한 뒤 coursework in progress에도 넣으라고 국제처에서 안내받은 사례가 있어요.
(담당자 답변 · 2026.07.23)

Q. Coursework in progress에 교양도 적어야 하나요?
A. 다 적었다는 학생과, 선수과목과 무관하면 큰 문제 없다고 들어 안 적었다는 학생이 나뉘어요.
(의견 엇갈림 · 2026.07.24)

Q. 지원서를 낸 뒤 고칠 수 있나요?
A. 국제처에 메일을 보내면 지원서를 되돌려 줬다는 사례가 여러 건 있어요.
(학생 경험담 · 2026.07.24)

Q. 지원서는 Submit만 누르면 끝인가요?
A. Submit 후 국제처 담당자에게 완료 메일을 보냈다는 학생이 많아요. 안내 메일의 제출 방법을 먼저 확인하세요.
(학생 경험담 · 2026.07.24)

[배정]

Q. 캠퍼스 배정 결과는 언제 나오나요?
A. 2026-1 기준 9월 3일부터 캠퍼스·단과대·학과별로 순차 발표됐어요. 국제처는 최대 10월까지 걸릴 수 있다고 안내했어요.
(담당자 답변 · 2026.09.07)

Q. 배정 결과는 어디서 확인하나요?
A. 메일이 오거나 My UC의 Details 맨 위에 표시돼요. 메일은 한국 시간 이른 아침에 온 사례가 많아요.
(학생 경험담 · 2026.09.12)

Q. Pending이면 배정된 건가요?
A. 사실상 배정으로 본 학생이 많지만 Placed로 확정 표시된 사례도 있어요. 메일과 Details의 안내를 함께 확인하세요.
(의견 엇갈림 · 2026.09.10)

Q. 지망하지 않은 캠퍼스의 study plan을 내라고 하면요?
A. 3개 지망이 안 된 경우 받은 사례가 있어요. My UC Details 아래 upload documents에 1차 OT 자료의 양식으로 올렸어요.
(학생 경험담 · 2026.09.20)

[학점 인정]

Q. 전공 학점은 누구에게 승인받나요?
A. 같은 과목으로 대체하면 해당 과목 교수, 무기명 전공선택이면 학과장 승인을 받는다고 알려져 있어요. 소속 학과에 확인하세요.
(학생 경험담 · 2026.07.23)

Q. 쿼터제 학점은 어떻게 환산되나요?
A. 쿼터 학점에 2/3를 곱해요. 4학점이 3학점으로 인정된 사례가 있지만, 과목별 반올림인지 전체 환산인지는 교무 쪽 확인이 필요해요.
(의견 엇갈림 · 2026.11.18)

Q. 대체 인정 과목명이 성적증명서에 나오나요?
A. 표기되지 않는다는 안내가 공유됐어요. 자격시험 등에 이수 증명이 필요한 과목은 본교에서 듣는 편이 안전해요.
(담당자 답변 · 2026.07.23)

[재정 증명]

Q. 주식 계좌로 잔고증명을 낼 수 있나요?
